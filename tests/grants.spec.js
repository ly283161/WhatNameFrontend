import { test, expect } from '@playwright/test'
const navigate=(page,name)=>page.locator('aside nav').getByRole('button',{name,exact:true}).click()
const grant=async(page,reason)=>{
 await page.getByLabel('授权理由').fill(reason)
 await page.getByRole('button',{name:'确认授权',exact:true}).click()
 await page.getByLabel('业务依据编号',{exact:true}).fill(reason==='项目支持'?'WORK-001':'WORK-002')
 await page.getByRole('button',{name:'继续确认',exact:true}).click()
 await page.getByRole('button',{name:'执行操作',exact:true}).click()
}
test('多条依据明确选择，保留其他来源，最后一条自动回收',async({page})=>{
 await page.goto('/')
 await navigate(page,'权限分配')
 for(const name of ['林晓','许文'])await page.getByRole('checkbox',{name:'选择'+name,exact:true}).check()
 await page.getByLabel('授权理由').fill('项目支持')
 await page.getByRole('button',{name:'确认授权',exact:true}).click()
 await expect(page.getByRole('dialog')).toContainText('项目支持')
 await page.getByRole('button',{name:'取消',exact:true}).click()
 expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('access-users')).find(u=>u.id==='U008').roles.includes('普通员工'))).toBe(false)
 await grant(page,'项目支持')
 await expect(page.getByLabel('权限操作结果')).toContainText('2 位用户')
 await page.getByRole('checkbox',{name:'选择许文',exact:true}).check()
 await grant(page,'第二项支持')
 await page.getByLabel('权限操作',{exact:true}).selectOption('revoke')
 await page.getByRole('checkbox',{name:'选择许文',exact:true}).check()
 await page.getByRole('button',{name:'确认回收',exact:true}).click()
 await expect(page.locator('.toast')).toContainText('请填写回收理由')
 await page.getByLabel('回收理由').fill('支持结束')
 await page.getByRole('button',{name:'确认回收',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'选择回收依据',exact:true})).toBeVisible()
 await page.screenshot({path:'.review-design-v3/回收依据选择.png',fullPage:true})
 await expect(page.getByRole('dialog').getByRole('checkbox',{checked:true})).toHaveCount(0)
 await page.getByRole('button',{name:'确认选择',exact:true}).click()
 await expect(page.locator('.toast')).toContainText('请选择有效的回收依据')
 await page.getByRole('checkbox',{name:'许文 · WORK-001',exact:true}).check()
 await page.getByRole('button',{name:'确认选择',exact:true}).click()
 await expect(page.getByRole('dialog')).toContainText('角色继续有效')
 await page.getByRole('button',{name:'取消',exact:true}).click()
 const unchanged=await page.evaluate(()=>JSON.parse(localStorage.getItem('access-users')).find(u=>u.id==='U008'))
 expect(unchanged.roleGrants.filter(g=>g.role==='普通员工'&&g.status==='有效')).toHaveLength(2)
 await page.getByRole('button',{name:'确认回收',exact:true}).click()
 await expect(page.getByRole('dialog').getByRole('checkbox',{checked:true})).toHaveCount(0)
 await page.getByRole('checkbox',{name:'许文 · WORK-001',exact:true}).check()
 await page.getByRole('button',{name:'确认选择',exact:true}).click()
 await page.getByRole('button',{name:'执行操作',exact:true}).click()
 await expect(page.getByLabel('权限操作结果')).toContainText('其他依据仍使角色有效')
 const remaining=await page.evaluate(()=>JSON.parse(localStorage.getItem('access-users')).find(u=>u.id==='U008'))
 expect(remaining.roleGrants.find(g=>g.basisId==='WORK-002').status).toBe('有效')
 await page.getByRole('checkbox',{name:'选择许文',exact:true}).check()
 await page.getByLabel('回收理由').fill('支持结束')
 await page.getByRole('button',{name:'确认回收',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'确认权限操作',exact:true})).toBeVisible()
 await expect(page.getByRole('dialog')).toContainText('该角色失效')
 await expect(page.getByRole('dialog').getByRole('checkbox')).toHaveCount(0)
 await page.getByRole('button',{name:'执行操作',exact:true}).click()
 const user=await page.evaluate(()=>JSON.parse(localStorage.getItem('access-users')).find(u=>u.id==='U008'))
 expect(user.roles).not.toContain('普通员工')
 expect(user.roles).toContain('运维工程师')
 expect(user.roleGrants.filter(g=>g.role==='普通员工').every(g=>g.revocationBasis==='支持结束')).toBe(true)
})

test('批量回收混合单条与多条依据，单条自动定位，每人必须有回收依据',async({page})=>{
 await page.goto('/')
 await page.evaluate(()=>{
  const users=JSON.parse(localStorage.getItem('access-users'))
  users.find(u=>u.id==='U008').roleGrants.push(
   {id:'mixed-a',role:'普通员工',basisType:'手工授权',basisId:'WORK-A',status:'有效'},
   {id:'mixed-b',role:'普通员工',basisType:'手工授权',basisId:'WORK-B',status:'有效'}
  )
  localStorage.setItem('access-users',JSON.stringify(users))
 })
 await page.reload()
 await navigate(page,'权限分配')
 await page.getByLabel('权限操作',{exact:true}).selectOption('revoke')
 for(const name of ['许文','周子墨'])await page.getByRole('checkbox',{name:'选择'+name,exact:true}).check()
 await page.getByLabel('回收理由').fill('业务结束')
 await page.getByRole('button',{name:'确认回收',exact:true}).click()
 const automatic=page.getByRole('checkbox',{name:'周子墨 · legacy-0',exact:true})
 await expect(automatic).toBeChecked()
 await expect(automatic).toBeDisabled()
 await page.getByRole('button',{name:'确认选择',exact:true}).click()
 await expect(page.locator('.toast')).toContainText('请为每位所选用户选择回收依据')
 await page.getByRole('checkbox',{name:'许文 · WORK-A',exact:true}).check()
 await page.getByRole('button',{name:'确认选择',exact:true}).click()
 await expect(page.getByRole('dialog')).toContainText('角色继续有效')
 await expect(page.getByRole('dialog')).toContainText('该角色失效')
 await page.getByRole('button',{name:'执行操作',exact:true}).click()
 const users=await page.evaluate(()=>JSON.parse(localStorage.getItem('access-users')))
 expect(users.find(u=>u.id==='U007').roles).not.toContain('普通员工')
 expect(users.find(u=>u.id==='U008').roles).toContain('普通员工')
 expect(users.find(u=>u.id==='U008').roleGrants.find(g=>g.id==='mixed-b').status).toBe('有效')
})
