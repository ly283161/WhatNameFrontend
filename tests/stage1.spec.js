import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'

const navigate = (page, label) => page.locator('aside nav').getByRole('button', { name: label, exact: true }).click()
async function signIn(page) {
  await page.goto('/')
  await page.getByRole('textbox', { name: '账号', exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('123456')
  const response = page.waitForResponse(r => r.url().endsWith('/auth/login') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  const data = (await (await response).json()).data
  await expect(page.getByRole('heading', { name: '工作台' })).toBeVisible()
  return { Authorization: 'Bearer ' + data.accessToken }
}
const submit = page => page.locator('.stage-form').getByRole('button', { name: '确认提交' }).click()
const api = async (page, headers, path, options = {}) => {
  const response = await page.request.fetch('/api/v1' + path, { headers, ...options })
  expect(response.ok()).toBe(true)
  return (await response.json()).data
}

