test('授权历史支持单选、多选和全部查询，合并排序分页、失败重试与按钮同行', async ({ page }) => {
  const headers = await signIn(page); await navigate(page, '权限分配')
  const users = (await api(page, headers, '/users?page=1&pageSize=20')).items
  const trigger = page.locator('.grant-controls').getByRole('button', { name: '查询授权历史', exact: true })
  const submit = page.locator('.grant-controls').getByRole('button', { name: '提交', exact: true })
  await expect(page.locator('.page-heading').getByRole('button', { name: '查询授权历史' })).toHaveCount(0)
  const modal = page.getByRole('dialog', { name: '授权历史', exact: true })
  function requestFor(userId, pageNumber = '1') { return page.waitForRequest(r => {
    const url = new URL(r.url())
    return url.pathname.endsWith('/grants/history') && (url.searchParams.get('userId') || '') === userId && url.searchParams.get('page') === pageNumber
  }) }
  const all = requestFor('')
  await trigger.click()
  const allUrl = new URL((await all).url())
  expect(allUrl.searchParams.has('roleId')).toBe(false)
  await expect(modal.getByText('全部授权历史', { exact: true })).toBeVisible()
  await expect(modal.getByLabel('历史用户 ID')).toHaveCount(0)
  await page.keyboard.press('Escape'); await expect(modal).toHaveCount(0); await expect(trigger).toBeFocused()
  let failUser = false
  await page.route('**/api/v1/grants/history?**', async route => {
    const params = new URL(route.request().url()).searchParams, pageNumber = Number(params.get('page')), pageSize = Number(params.get('pageSize'))
    if (failUser && params.get('userId') === users[1].userId) { await route.fulfill({ status: 500, json: { success: false, code: 'INTERNAL', message: '授权历史查询失败' } }); return }
    const items = Array.from({ length: Math.max(0, Math.min(pageSize, 21 - (pageNumber - 1) * pageSize)) }, (_, index) => ({ eventId: String((pageNumber - 1) * pageSize + index + 1), userId: params.get('userId'), roleId: params.get('roleId'), operation: 'GRANT', grantSourceId: String(index + 1), occurredAt: params.get('userId') === users[0].userId ? '2026-10-20T10:00:00+08:00' : '2026-10-19T10:00:00+08:00' }))
    await route.fulfill({ json: { success: true, code: 'OK', data: { items, total: 21, page: pageNumber, pageSize } } })
  })
  const boxes = page.locator('.table-panel tbody input[type=checkbox]')
  await boxes.nth(0).check()
  const role = await page.getByLabel('角色', { exact: true }).inputValue()
  const selected = requestFor(users[0].userId)
  await trigger.click()
  expect(new URL((await selected).url()).searchParams.get('roleId')).toBe(role)
  await expect(modal.getByText(users[0].realName, { exact: false }).first()).toBeVisible()
  const next = requestFor(users[0].userId, '2')
  await modal.getByRole('button', { name: '下一页', exact: true }).click(); await next
  await expect(modal.getByText('共 21 条 · 第 2 页')).toBeVisible()
  await modal.getByRole('button', { name: '关闭授权历史' }).click()
  await expect(trigger).toBeFocused()
  await expect.poll(() => page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
  await boxes.nth(1).check(); await expect(trigger).toBeEnabled()
  const multiple = [requestFor(users[0].userId), requestFor(users[1].userId)]
  await trigger.click(); await Promise.all(multiple)
  await expect(modal.getByText('已选 2 位用户：', { exact: false })).toBeVisible()
  await expect(modal.getByText('共 42 条 · 第 1 页')).toBeVisible()
  await expect(modal.locator('tbody tr').first().locator('td').first()).toHaveText(users[0].userId)
  await modal.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(modal.getByText('共 42 条 · 第 2 页')).toBeVisible()
  await modal.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(modal.getByText('共 42 条 · 第 3 页')).toBeVisible()
  await expect(modal.locator('tbody tr')).toHaveCount(2)
  await expect(modal.locator('tbody tr').first().locator('td').first()).toHaveText(users[1].userId)
  await page.keyboard.press('Escape')
  failUser = true
  await trigger.click()
  await expect(modal.getByRole('alert')).toContainText('授权历史查询失败')
  await expect(modal.locator('tbody tr')).toHaveCount(0)
  failUser = false
  await modal.getByRole('button', { name: '重新加载', exact: true }).click()
  await expect(modal.getByText('共 42 条 · 第 1 页')).toBeVisible()
  await page.keyboard.press('Escape')
  await boxes.nth(0).uncheck(); await expect(trigger).toBeEnabled()
  const second = requestFor(users[1].userId)
  await trigger.click(); await second
  await expect(modal.getByText(users[1].realName, { exact: false }).first()).toBeVisible()
  await page.keyboard.press('Escape')
  for (const width of [1280, 390]) {
    await page.setViewportSize({ width, height: 850 })
    const a = await submit.boundingBox(), b = await trigger.boundingBox()
    expect(Math.abs(a.y + a.height / 2 - b.y - b.height / 2)).toBeLessThan(2)
    expect(b.x).toBeGreaterThan(a.x)
  }
})
